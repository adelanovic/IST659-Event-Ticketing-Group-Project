"""
Turn the CSVs in data/csv/ into SQL Server INSERT statements.

    python generate_inserts.py

Writes sql/insert_ticketmaster_data.sql, ready to paste into the UP section of
the project's SQL file (after the CREATE TABLEs). Re-run it whenever the CSVs or
the schema change.

If the final schema uses different table or column names, edit TABLES below:
the key is the CSV file, "table" is the SQL table name, and "columns" maps each
CSV column to its SQL column name (leave a column out to skip it).
"""

import csv
from pathlib import Path

ROOT = Path(__file__).parent
CSV_DIR = ROOT / "data" / "csv"
OUT = ROOT / "sql" / "insert_ticketmaster_data.sql"
BATCH = 1000            # SQL Server's limit for rows in one INSERT ... VALUES

# Load order matters: parents before children, so foreign keys always resolve.
TABLES = {
    "genres": {
        "table": "dbo.genres",
        "identity": True,
        "columns": {"genre_id": "genre_id", "name": "name"},
    },
    "venues": {
        "table": "dbo.venues",
        "identity": True,
        "columns": {"venue_id": "venue_id", "name": "name",
                    "address": "address", "city": "city", "state": "state",
                    "postal_code": "postal_code"},
    },
    "artists": {
        "table": "dbo.artists",
        "identity": True,
        "columns": {"artist_id": "artist_id", "name": "name", "genre_id": "genre_id"},
    },
    "events": {
        "table": "dbo.events",
        "identity": True,
        "columns": {"event_id": "event_id", "name": "name",
                    "venue_id": "venue_id", "event_date": "event_date",
                    "event_time": "event_time", "status": "status"},
    },
    "event_artists": {
        "table": "dbo.event_artists",
        "identity": False,
        "columns": {"event_id": "event_id", "artist_id": "artist_id",
                    "billing_order": "billing_order"},
    },
}

# CSV columns written as bare numbers; everything else is quoted text.
NUMERIC = {"genre_id", "venue_id", "artist_id", "event_id", "billing_order"}


def sql_value(column, value):
    if value == "":
        return "NULL"
    if column in NUMERIC:
        int(value)                       # fail loudly on bad data instead of writing bad SQL
        return value
    return "N'" + value.replace("'", "''") + "'"


def table_sql(csv_name, spec):
    with open(CSV_DIR / f"{csv_name}.csv", newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    csv_cols = list(spec["columns"])
    col_list = ", ".join(spec["columns"][c] for c in csv_cols)

    out = [f"-- {spec['table']}: {len(rows)} rows from data/csv/{csv_name}.csv"]
    if spec["identity"]:
        out.append(f"SET IDENTITY_INSERT {spec['table']} ON;")
    for start in range(0, len(rows), BATCH):
        chunk = rows[start:start + BATCH]
        values = ",\n".join(
            "(" + ", ".join(sql_value(c, r[c]) for c in csv_cols) + ")" for r in chunk)
        out.append(f"INSERT INTO {spec['table']} ({col_list}) VALUES\n{values};")
    if spec["identity"]:
        out.append(f"SET IDENTITY_INSERT {spec['table']} OFF;")
    out.append("GO\n")
    return "\n".join(out), len(rows)


def main():
    parts = [
        "-- Ticketmaster data for the concert ticketing database.",
        "-- Generated by generate_inserts.py from data/csv/. Do not edit by hand; re-run the script.",
        "-- Run after the CREATE TABLE statements.",
        "SET NOCOUNT ON;",
        "GO\n",
    ]
    for csv_name, spec in TABLES.items():
        sql, n = table_sql(csv_name, spec)
        parts.append(sql)
        print(f"  {spec['table']:<20}{n:>6} rows")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
